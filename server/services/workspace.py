import uuid


def create_expert_interview_meet(candidate_email: str, expert_email: str, date: str) -> str:
    """
    Creates a Google Meet link for an expert interview session.

    In a full production environment, this function would:
    1. Authenticate with Google Workspace using OAuth2
    2. Create a Calendar event via the Calendar API
    3. Enable conferenceDataVersion=1 to auto-generate Meet link
    4. Send calendar invites to both candidate and expert

    For this hackathon, we generate a simulated Meet link.

    Args:
        candidate_email: Email address of the candidate being interviewed
        expert_email: Email address of the expert conducting the interview
        date: Interview date and time (ISO 8601 format)

    Returns:
        str: Google Meet link (e.g., "https://meet.google.com/abc123xyz")

    Example:
        >>> link = create_expert_interview_meet(
        ...     "candidate@example.com",
        ...     "expert@example.com",
        ...     "2026-05-15T10:00:00Z"
        ... )
        >>> print(link)
        'https://meet.google.com/a1b2c3d4e5'
    """
    # Generate a random Meet link ID (simulation)
    # Real Meet links are generated by Google Calendar API
    mock_meet_id = str(uuid.uuid4())[:10]

    return f"https://meet.google.com/{mock_meet_id}"
